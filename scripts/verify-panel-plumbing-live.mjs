// verify-panel-plumbing-live.mjs — run the T9 shared-panel-plumbing checks against a DEPLOYED site.
//
// WHY THIS EXISTS. A green guard on a laptop proves the source is right. It does not prove the
// SITE is right: the panels are static assets behind a cache that vercel.json lets go stale for up
// to 24h, and this project has twice had a device running a weeks-old panel whose bug was already
// fixed. So this downloads each panel file FROM THE LIVE URL and runs the identical static checks
// against the bytes the site is actually serving, then reports the served content hash beside the
// one the local file has — if a device could be handed something different, it says so.
//
//   node scripts/verify-panel-plumbing-live.mjs --base https://3-d-backup.vercel.app
//
// It makes GET requests for static files only. It signs in to nothing, writes nothing, and touches
// no restaurant's data — so it is safe to point at any deployed stack, and cheap enough to re-run
// after every deploy.
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { requireUp } from "./sweep/appUp.mjs";

const argv = process.argv.slice(2);
const baseArg = argv.includes("--base") ? argv[argv.indexOf("--base") + 1] : null;
if (!baseArg) {
  console.error("verify-panel-plumbing-live: --base <url> is required (e.g. https://3-d-backup.vercel.app)");
  process.exit(2);
}
const BASE = baseArg.replace(/\/+$/, "");
// Nothing answering = "could not run" (exit 2), said in plain words — never a raw ECONNREFUSED
// stack, which reads as "this guard is broken". (sweep #6 / T28, 2026-08-22)
await requireUp(BASE, "the deployed-plumbing comparison");
const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..");

// Everything the plumbing guard reads, at the path the panels load it from.
const FILES = [
  "backstack.js", "undobar.js", "realtime.js", "connbadge.js", "guestbell.js", "swipehint.js",
  "theme.js", "fitnums.js", "myprofile.js", "errlog.js", "maint.js", "issue-raise.js",
  "outbox.js", "editor/inventory.js",
];

const mirror = mkdtempSync(join(tmpdir(), "lfh-live-panels-"));
mkdirSync(join(mirror, "public/panels/editor"), { recursive: true });
mkdirSync(join(mirror, "public/panels/vendor"), { recursive: true });

const sha8 = (buf) => createHash("sha1").update(buf).digest("hex").slice(0, 8);
const drift = [];
let fetched = 0;

console.log(`checking the panels the SITE is serving — ${BASE}\n`);

for (const f of FILES) {
  const url = `${BASE}/panels/${f}`;
  let res;
  try { res = await fetch(url, { cache: "no-store" }); }
  catch (e) { console.error(`  ✗ ${f} — could not be fetched (${e.message})`); process.exitCode = 1; continue; }
  if (!res.ok) { console.error(`  ✗ ${f} — the site answered ${res.status}`); process.exitCode = 1; continue; }
  const body = Buffer.from(await res.arrayBuffer());
  writeFileSync(join(mirror, "public/panels", f), body);
  fetched++;
  // Is the site serving the same bytes this checkout has?
  let local = null;
  try { local = readFileSync(join(REPO, "public/panels", f)); } catch { /* not in this checkout */ }
  const served = sha8(body);
  if (local && sha8(local) !== served) drift.push({ f, served, local: sha8(local) });
}

// the charts library too, since its version is now a fact rather than a label
try {
  const r = await fetch(`${BASE}/panels/vendor/chart.umd.min.js`, { cache: "no-store" });
  if (r.ok) {
    const b = Buffer.from(await r.arrayBuffer());
    writeFileSync(join(mirror, "public/panels/vendor/chart.umd.min.js"), b);
    const banner = /chart\.js v([0-9.]+) — generated by scripts\/build-vendor\.mjs/.exec(b.toString("utf8").slice(0, 200));
    console.log(banner
      ? `  · the site's charts library says it is v${banner[1]}, generated by the build script`
      : "  ✗ the site's charts library carries no generated banner — it is a hand-copied file");
    if (!banner) process.exitCode = 1;
  }
} catch { /* the guard below will not check it, and says so */ }

console.log(`  · fetched ${fetched} of ${FILES.length} panel files from the site\n`);

// package.json + the two scripts the guard also reads, taken from THIS checkout: they are not
// served to a browser, so the deployed site cannot disagree about them.
for (const p of ["package.json", "scripts/build-vendor.mjs", "scripts/verify-panel-cache.mjs"]) {
  try {
    mkdirSync(dirname(join(mirror, p)), { recursive: true });
    writeFileSync(join(mirror, p), readFileSync(join(REPO, p)));
  } catch { /* the guard tolerates a missing file */ }
}

const run = spawnSync(process.execPath, [join(HERE, "verify-panel-plumbing.mjs"), mirror], { encoding: "utf8" });
process.stdout.write(run.stdout || "");
process.stderr.write(run.stderr || "");

if (drift.length) {
  console.error(`\n✗ ${drift.length} file(s) the SITE serves differ from this checkout:\n`);
  for (const d of drift) console.error(`  · ${d.f}  site=${d.served}  here=${d.local}`);
  console.error("\nEither the deploy has not finished, or a cache is still handing out the old file.");
  process.exit(1);
}
if (run.status !== 0) process.exit(run.status || 1);
if (process.exitCode) process.exit(process.exitCode);
console.log(`\n✓ the deployed site at ${BASE} is serving the checked plumbing, byte-for-byte`);
